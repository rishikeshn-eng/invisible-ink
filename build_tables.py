"""Build invisible_ink/_tables.py from the Unicode Character Database files.

Run once (offline) to regenerate the frozen tables the scanner uses. Keeping the
tables generated from the real UCD — rather than hand-typed — means detection is
grounded in the standard and easy to refresh for a new Unicode version.
"""
from __future__ import annotations

import os
import re
import sys

UCD = sys.argv[1] if len(sys.argv) > 1 else "../rawdata/unicode"
OUT = sys.argv[2] if len(sys.argv) > 2 else "invisible_ink/_tables.py"


def ranges_from(path, prop_filter=None):
    """Yield (start, end) code-point ranges from a UCD list file, optionally filtered by property."""
    out = []
    with open(os.path.join(UCD, path), encoding="utf-8") as f:
        for line in f:
            line = line.split("#", 1)[0].strip()
            if not line:
                continue
            parts = [p.strip() for p in line.split(";")]
            cps = parts[0]
            if prop_filter is not None:
                if len(parts) < 2 or parts[1] != prop_filter:
                    continue
            if ".." in cps:
                a, b = cps.split("..")
            else:
                a = b = cps
            out.append((int(a, 16), int(b, 16)))
    return _merge(out)


def _merge(ranges):
    ranges = sorted(ranges)
    merged = []
    for a, b in ranges:
        if merged and a <= merged[-1][1] + 1:
            merged[-1] = (merged[-1][0], max(merged[-1][1], b))
        else:
            merged.append((a, b))
    return merged


def scripts_map():
    """code-point range -> script name (from Scripts.txt)."""
    out = []
    with open(os.path.join(UCD, "Scripts.txt"), encoding="utf-8") as f:
        for line in f:
            line = line.split("#", 1)[0].strip()
            if not line:
                continue
            cps, name = [p.strip() for p in line.split(";")]
            a, b = (cps.split("..") + [cps])[:2] if ".." in cps else (cps, cps)
            out.append((int(a, 16), int(b, 16), name))
    return sorted(out)


def confusables_skeleton():
    """source code point (single) -> target string (its 'prototype'), from confusables.txt.

    We keep only single-source mappings (the common homoglyph case) and store the
    target as a tuple of code points.
    """
    out = {}
    with open(os.path.join(UCD, "confusables.txt"), encoding="utf-8") as f:
        for line in f:
            if line.startswith("#") or ";" not in line:
                continue
            parts = line.split(";")
            if len(parts) < 2:
                continue
            src = parts[0].strip().split()
            tgt = parts[1].strip().split()
            if len(src) != 1:
                continue
            try:
                s = int(src[0], 16)
                t = tuple(int(x, 16) for x in tgt)
            except ValueError:
                continue
            out[s] = t
    return out


def main():
    default_ignorable = ranges_from("DerivedCoreProperties.txt", "Default_Ignorable_Code_Point")
    bidi_control = ranges_from("PropList.txt", "Bidi_Control")
    join_control = ranges_from("PropList.txt", "Join_Control")
    noncharacter = ranges_from("PropList.txt", "Noncharacter_Code_Point")
    variation_selector = ranges_from("PropList.txt", "Variation_Selector")
    white_space = ranges_from("PropList.txt", "White_Space")
    deprecated = ranges_from("PropList.txt", "Deprecated")

    scripts = scripts_map()
    conf = confusables_skeleton()

    # Latin look-alikes: confusable sources whose prototype is pure ASCII/Latin, and the
    # source itself is NOT Latin/Common — i.e. a non-Latin glyph masquerading as Latin.
    script_of = _script_lookup(scripts)
    latin_conf = {}
    for s, t in conf.items():
        if all(cp < 0x80 for cp in t):      # prototype is ASCII
            sc = script_of(s)
            if sc not in ("Latin", "Common", "Inherited") and s >= 0x80:
                latin_conf[s] = "".join(chr(c) for c in t)

    with open(OUT, "w", encoding="utf-8") as f:
        f.write('"""Frozen Unicode tables — generated by build_tables.py from the UCD. Do not edit by hand."""\n')
        f.write("# Unicode version source: data files under rawdata/unicode\n\n")
        _emit(f, "DEFAULT_IGNORABLE", default_ignorable)
        _emit(f, "BIDI_CONTROL", bidi_control)
        _emit(f, "JOIN_CONTROL", join_control)
        _emit(f, "NONCHARACTER", noncharacter)
        _emit(f, "VARIATION_SELECTOR", variation_selector)
        _emit(f, "WHITE_SPACE", white_space)
        _emit(f, "DEPRECATED", deprecated)
        f.write(f"SCRIPTS = {scripts!r}\n\n")
        f.write(f"LATIN_CONFUSABLES = {latin_conf!r}\n\n")
        f.write(f"CONFUSABLE_COUNT = {len(conf)}\n")
        f.write(f"LATIN_CONFUSABLE_COUNT = {len(latin_conf)}\n")

    print(f"wrote {OUT}")
    print(f"  default_ignorable ranges: {len(default_ignorable)}")
    print(f"  bidi_control ranges: {len(bidi_control)}")
    print(f"  variation_selector ranges: {len(variation_selector)}")
    print(f"  scripts: {len(scripts)} ranges")
    print(f"  confusables: {len(conf)} single-source; {len(latin_conf)} masquerade-as-Latin")


def _script_lookup(scripts):
    starts = [s for s, _, _ in scripts]
    import bisect

    def f(cp):
        i = bisect.bisect_right(starts, cp) - 1
        if 0 <= i < len(scripts):
            a, b, name = scripts[i]
            if a <= cp <= b:
                return name
        return "Unknown"
    return f


def _emit(f, name, ranges):
    f.write(f"{name} = {ranges!r}\n\n")


if __name__ == "__main__":
    main()
